// Builds the portal into one self-contained page: crates/core/src/ui.html (inline script and style, no external
// requests), which build.rs then embeds and gzips. Usage:  node build.mjs [--check]
//   --check  build in memory and fail if the committed page differs (CI and check.sh use this).
import * as esbuild from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => join(here, "src", f);
const out = join(here, "..", "crates", "core", "src", "ui.html");
const check = process.argv.includes("--check");

const js = await esbuild.build({
  entryPoints: [src("main.tsx")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2022",
  jsx: "automatic",
  jsxImportSource: "preact",
  legalComments: "none",
  write: false,
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});
// styles/index.css imports tokens.css and every area's partial; the import order is the cascade order.
const css = await esbuild.build({
  entryPoints: [src("styles/index.css")],
  bundle: true,
  minify: true,
  write: false,
  logLevel: "warning",
});

const script = js.outputFiles[0].text.trimEnd();
const style = css.outputFiles[0].text.trimEnd();
// A closing tag inside the inline script or style would end it early (esbuild escapes these; this guards the guard).
for (const [what, text, tag] of [
  ["script", script, "</script"],
  ["style", style, "</style"],
]) {
  if (text.toLowerCase().includes(tag)) throw new Error(`the built ${what} contains ${tag}`);
}

const shell = readFileSync(src("index.html"), "utf8");
if (!shell.includes("/*@css*/") || !shell.includes("/*@js*/"))
  throw new Error("index.html lost its /*@css*/ or /*@js*/ marker");
const banner =
  "<!-- Generated by portal/build.mjs from portal/src. Do not edit; edit portal/src and run `npm run build` in portal/. -->\n";
// Replacement functions, never strings: the bundle contains `$&`-style sequences.
const page = shell
  .replace("<!doctype html>\n", () => "<!doctype html>\n" + banner)
  .replace("/*@css*/", () => style)
  .replace("/*@js*/", () => script);

if (check) {
  let have = "";
  try {
    have = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (have !== page) {
    console.error(
      "portal: crates/core/src/ui.html is out of date. Run `npm run build` in portal/ and commit the result.",
    );
    process.exit(1);
  }
  console.log(`portal: ui.html is current (${Buffer.byteLength(page)} bytes)`);
} else {
  writeFileSync(out, page);
  console.log(`portal: wrote ${out} (${Buffer.byteLength(page)} bytes)`);
}
